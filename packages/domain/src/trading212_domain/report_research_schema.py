RESEARCH_MEMBER_FIELDS = {
    "portfolio": frozenset({"source_reference_ids", "metric_source_reference_ids", "path_keys"}),
    "warning": frozenset({"source_reference_ids", "path_keys"}),
}


def validate_research_report_relation(table: ReportTableKey, row: ReportRow) -> None:
    if table is ReportTableKey.RESEARCH_PORTFOLIO_MEMBERS_V1:
        owner, _, field, ordinal, _ = (cell.value for cell in row.cells)
        if (
            type(owner) is not str
            or type(field) is not str
            or field not in RESEARCH_MEMBER_FIELDS.get(owner, frozenset())
            or type(ordinal) is not int
            or ordinal < 0
        ):
            fail_validation("Research membership is outside its fixed schema.", field="row")
    if table is ReportTableKey.RESEARCH_SOURCE_LICENSES_V1 and row.cells[0].value not in {
        "pinned",
        "current",
    }:
        fail_validation("Research license role is invalid.", field="row")
