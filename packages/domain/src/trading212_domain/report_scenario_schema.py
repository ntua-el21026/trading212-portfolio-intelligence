# This relation preserves ordered fields from closed canonical records. It cannot
# be used as a generic property bag or an extension registration endpoint.
SCENARIO_MEMBER_FIELDS: dict[str, frozenset[str]] = {
    "calculation": frozenset({"upstream_residual_keys", "assumptions"}),
    "exposure": frozenset({"source_reference_ids"}),
    "subject": frozenset({"identity_decision_ids", "source_reference_ids"}),
    "classification": frozenset({"assignment_ids", "evidence_ids", "source_reference_ids"}),
    "economic_currency": frozenset({"assignment_ids", "evidence_ids", "source_reference_ids"}),
    "component": frozenset({"matching_exclusion_keys", "uncertain_rule_keys", "diagnostic_keys"}),
    "metric": frozenset({"source_reference_ids"}),
    "applied_sensitivity": frozenset({"candidate_observation_ids", "evidence_reference_ids"}),
    "sensitivity_driver": frozenset({"evidence_reference_ids"}),
    "sensitivity_observation": frozenset({"evidence_reference_ids"}),
    "diagnostic": frozenset({"source_reference_ids", "source_use_keys"}),
    "replay_change": frozenset({"source_use_keys", "conversion_keys"}),
    "replay_binding": frozenset({"source_reference_ids"}),
    "replay_context": frozenset({"assumptions", "source_reference_ids"}),
    "replay_coverage": frozenset({"reasons"}),
    "replay_warning": frozenset({"reference_ids"}),
}


def validate_scenario_report_relation(table: ReportTableKey, row: "ReportRow") -> None:
    """Check new closed proof labels after the unchanged column/scalar validation."""
    if table is ReportTableKey.SCENARIO_MEMBERS_V1:
        owner, _, field, ordinal, _ = (cell.value for cell in row.cells)
        if (
            type(owner) is not str
            or type(field) is not str
            or field not in SCENARIO_MEMBER_FIELDS.get(owner, frozenset())
            or type(ordinal) is not int
            or ordinal < 0
        ):
            fail_validation(
                "Scenario proof membership is outside its fixed relation.", field="cells"
            )
    elif table is ReportTableKey.SCENARIO_SOURCE_HEADERS_V1:
        if row.cells[0].value not in {
            "scenario_sensitivity_version",
            "scenario_sensitivity_observation",
            "scenario_sensitivity_evidence",
        }:
            fail_validation("Scenario original source header kind is invalid.", field="cells")
