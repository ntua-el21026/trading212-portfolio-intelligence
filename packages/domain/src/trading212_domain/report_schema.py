def _column(key: str, code: str) -> ReportColumn:
    if code in {"N", "N?"}:
        return ReportColumn(key=key, kind=None, optional=code.endswith("?"))
    optional = code.endswith("?")
    code = code.removesuffix("?")
    kinds = {
        "id": CellKind.IDENTIFIER,
        "text": CellKind.TEXT,
        "enum": CellKind.ENUM,
        "date": CellKind.DATE,
        "utc": CellKind.INSTANT,
        "int": CellKind.INTEGER,
        "bool": CellKind.BOOLEAN,
    }
    if code in kinds:
        return ReportColumn(key=key, kind=kinds[code], optional=optional)
    roles = {
        "M": DecimalRole.MONEY,
        "R": DecimalRole.RATIO,
        "Q": DecimalRole.QUANTITY,
        "D": DecimalRole.SCORE,
        "D(price)": DecimalRole.PRICE,
        "D(fx)": DecimalRole.FX,
        "D(score)": DecimalRole.SCORE,
        "D(residual)": DecimalRole.RESIDUAL,
        "D(money)": DecimalRole.MONEY,
    }
    return ReportColumn(key=key, kind=CellKind.DECIMAL, decimal_role=roles[code], optional=optional)


@lru_cache(maxsize=128)
def table_schema(table: ReportTableKey) -> ReportTableSchema:
    if type(table) is not ReportTableKey or table not in _COLUMNS:
        fail_validation("Report table is not registered.", field="table")
    return ReportTableSchema(
        key=table, columns=tuple(_column(key, code) for key, code in _COLUMNS[table])
    )


def validate_report_row(table: ReportTableKey, row: ReportRow) -> None:
    schema = table_schema(table)
    if type(row) is not ReportRow or len(row.cells) != len(schema.columns):
        fail_validation("Report row columns differ from the registered table.", field="cells")
    for column, cell in zip(schema.columns, row.cells, strict=True):
        if column.kind is None:
            if cell.kind not in {CellKind.DECIMAL, CellKind.INTEGER, CellKind.BOOLEAN}:
                fail_validation(
                    "Report metric column requires a typed numeric or boolean cell.", field="cells"
                )
        elif cell.kind is not column.kind or cell.decimal_role is not column.decimal_role:
            fail_validation("Report cell type differs from its fixed column.", field="cells")
        if cell.state is CellState.NOT_APPLICABLE and not column.optional:
            fail_validation("Required report column cannot be inapplicable.", field="cells")


def section_tables(section: ReportSection) -> tuple[ReportTableKey, ...]:
    if type(section) is not ReportSection:
        fail_validation("Report section is invalid.", field="section")
    return _SECTION_TABLES[section]


