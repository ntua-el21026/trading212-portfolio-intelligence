_DATASET_SECTIONS = {
    ExportDataset.POSITIONS: (ReportSection.ALLOCATION, ReportSection.OVERVIEW),
    ExportDataset.ACTIVITY: (ReportSection.ACTIVITY,),
    ExportDataset.TARGETS: (ReportSection.TARGETS,),
    ExportDataset.PLANS: (ReportSection.CONTRIBUTION_PLAN,),
    ExportDataset.PERFORMANCE: (ReportSection.PERFORMANCE,),
    ExportDataset.XRAY: (ReportSection.XRAY,),
}


def dataset_tables(dataset: ExportDataset, field_set: ExportFieldSet) -> tuple[ReportTableKey, ...]:
    if type(dataset) is not ExportDataset or type(field_set) is not ExportFieldSet:
        fail_validation("Canonical export dataset is unavailable.", field="dataset")
    if dataset is ExportDataset.ALERTS:
        selected = set(ALERT_EXPORT_TABLES)
    elif dataset is ExportDataset.DIVIDENDS:
        selected = {ReportTableKey.DIVIDENDS}
    else:
        selected = {
            table for section in _DATASET_SECTIONS[dataset] for table in section_tables(section)
        }
    if dataset is ExportDataset.POSITIONS:
        selected.discard(ReportTableKey.ALLOCATION_BUCKETS)
    if dataset is ExportDataset.PLANS and field_set is ExportFieldSet.AUDIT:
        selected.update(section_tables(ReportSection.DRIFT))
    return tuple(table for table in ReportTableKey if table in selected)


def report_tables(selection: ReportSelection | ExportSelection) -> tuple[ReportTableKey, ...]:
    if isinstance(selection, ExportSelection):
        return dataset_tables(selection.dataset, selection.field_set)
    selected = {table for section in selection.sections for table in section_tables(section)}
    return tuple(table for table in ReportTableKey if table in selected)
