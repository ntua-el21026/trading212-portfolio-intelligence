"""Exactly five public capability projections from authoritative normalized headers.

This is readiness metadata, never an acquisition/read authorization substitute.
Original/current acquisition authority still independently authorizes every use.
"""

STATUS_SQL = (
    "\n"
    "WITH fixed(ordinal,provider_key,capability,research) AS (VALUES\n"
    " (0,'alpha_vantage','daily_adjusted',false),\n"
    " (1,'alpha_vantage','etf_profile',false),\n"
    " (2,'alpha_vantage','company_overview',true),\n"
    " (3,'alpha_vantage','news_sentiment',true),\n"
    " (4,'ecb','reference_fx',false)),\n"
    "research_permission AS (\n"
    " SELECT :research_token AND EXISTS(SELECT 1 FROM "
    "principal_scope_grants g\n"
    " WHERE g.principal_id=:principal AND g.scope='research:read'\n"
    " AND g.granted_at<=:at AND g.revoked_at IS NULL\n"
    " AND (g.expires_at IS NULL OR g.expires_at>:at)) AS allowed)\n"
    "SELECT f.ordinal,f.provider_key,f.capability,\n"
    " COALESCE(p.configuration_state='configured',false) AS "
    "provider_configured,\n"
    " (NOT f.research OR permission.allowed) AS research_allowed,\n"
    " COALESCE(policy.enabled AND policy.effective_at<=:at AND "
    "policy.expires_at>:at\n"
    "          AND policy.daily_allowance>0,false) AS policy_enabled,\n"
    " COALESCE(candidate.rights_allowed,false) AS rights_allowed,\n"
    " COALESCE(candidate.metadata_ready,false) AS metadata_ready,\n"
    " CASE WHEN candidate.rights_allowed THEN least(\n"
    "  CASE WHEN f.provider_key='ecb' THEN 24 ELSE 25 END,\n"
    "  policy.daily_allowance,candidate.daily_allowance) ELSE NULL "
    "END AS daily_allowance,\n"
    " CASE WHEN candidate.rights_allowed THEN "
    "COALESCE(day.charged_attempts,0) ELSE NULL END AS "
    "attempts_charged,\n"
    " CASE WHEN candidate.rights_allowed AND active.finished_at IS "
    "NULL\n"
    "  AND active.lease_expires_at>:at THEN active.lease_expires_at "
    "ELSE NULL END AS inflight_until\n"
    "FROM fixed f CROSS JOIN research_permission permission\n"
    "LEFT JOIN market_data_providers p ON p.owner_id=:owner AND "
    "p.key=f.provider_key\n"
    "LEFT JOIN LATERAL (SELECT v.* FROM provider_acquisition_policies "
    "v\n"
    " WHERE v.owner_id=:owner AND v.provider_id=p.id AND "
    "v.effective_at<=:at\n"
    " ORDER BY v.effective_at DESC,v.version_number DESC,v.id DESC "
    "LIMIT 1) policy ON true\n"
    "LEFT JOIN LATERAL (SELECT v.* FROM provider_license_versions v\n"
    " WHERE v.owner_id=:owner AND v.provider_id=p.id AND "
    "v.effective_at<=:at\n"
    " ORDER BY v.effective_at DESC,v.version_number DESC,v.id DESC "
    "LIMIT 1) license ON true\n"
    "LEFT JOIN LATERAL (\n"
    " SELECT true AS rights_allowed,g.daily_allowance,\n"
    "  (m.id IS NOT NULL AND m.effective_at<=:at AND m.expires_at>:at\n"
    "   AND (m.market_mapping_id IS NULL OR (market.id IS NOT NULL "
    "AND market.state='resolved'\n"
    "    AND market.instrument_id IS NOT NULL AND "
    "market.valid_from<=:at AND (market.valid_to IS NULL OR "
    "market.valid_to>:at)))\n"
    "   AND (m.calendar_id IS NULL OR calendar.id IS NOT NULL)\n"
    "   AND (m.source_series_id IS NULL OR (series.id IS NOT NULL AND "
    "market.id IS NOT NULL\n"
    "    AND series.mapping_id=market.id AND series.provider_id=p.id "
    "AND series.calendar_id=calendar.id\n"
    "    AND series.currency=market.currency AND "
    "series.instrument_id=market.instrument_id\n"
    "    AND series.license_version_id=g.license_version_id AND "
    "series.basis='raw_close')) AND\n"
    "   CASE WHEN f.capability='reference_fx' THEN\n"
    "      s.subject_kind='reference_fx' AND s.subject_id IS NULL AND "
    "calendar.id IS NOT NULL\n"
    "   ELSE market.id IS NOT NULL AND market.state='resolved' AND "
    "market.instrument_id IS NOT NULL\n"
    "      AND market.valid_from<=:at AND (market.valid_to IS NULL OR "
    "market.valid_to>:at)\n"
    "      AND CASE WHEN f.capability IN "
    "('daily_adjusted','etf_profile') THEN\n"
    "         s.subject_kind='instrument' AND "
    "s.subject_id=market.instrument_id AND instrument.id IS NOT NULL\n"
    "       ELSE s.subject_kind='entity' AND entity.id IS NOT NULL "
    "END\n"
    "      AND (f.capability<>'daily_adjusted' OR (calendar.id IS NOT "
    "NULL\n"
    "       AND series.id IS NOT NULL AND series.mapping_id=market.id\n"
    "       AND series.provider_id=p.id AND "
    "series.calendar_id=calendar.id\n"
    "       AND series.currency=market.currency AND "
    "series.instrument_id=market.instrument_id\n"
    "       AND series.license_version_id=g.license_version_id AND "
    "series.basis='raw_close'))\n"
    "   END) AS metadata_ready\n"
    " FROM provider_capability_scopes s\n"
    " JOIN LATERAL (SELECT v.* FROM provider_capability_grants v\n"
    "  WHERE v.owner_id=:owner AND v.scope_id=s.id AND "
    "v.effective_at<=:at\n"
    "  ORDER BY v.effective_at DESC,v.version_number DESC,v.id DESC "
    "LIMIT 1) g ON true\n"
    " LEFT JOIN LATERAL (SELECT v.* FROM "
    "provider_acquisition_mappings v\n"
    "  WHERE v.owner_id=:owner AND v.scope_id=s.id AND "
    "v.effective_at<=:at\n"
    "  ORDER BY v.effective_at DESC,v.version_number DESC,v.id DESC "
    "LIMIT 1) m ON true\n"
    " LEFT JOIN market_data_instruments market ON "
    "market.owner_id=:owner\n"
    "  AND market.provider_id=p.id AND market.id=m.market_mapping_id\n"
    " LEFT JOIN instruments instrument ON "
    "instrument.id=market.instrument_id\n"
    " LEFT JOIN economic_entities entity ON entity.owner_id=:owner "
    "AND entity.id=s.subject_id\n"
    " LEFT JOIN source_calendars calendar ON calendar.owner_id=:owner "
    "AND calendar.id=m.calendar_id\n"
    " LEFT JOIN market_source_series series ON series.owner_id=:owner "
    "AND series.id=m.source_series_id\n"
    " WHERE s.owner_id=:owner AND s.provider_id=p.id AND "
    "s.capability=f.capability\n"
    " AND (NOT f.research OR permission.allowed)\n"
    " AND g.provider_id=p.id AND g.license_version_id=license.id\n"
    " AND g.effective_at<=:at AND g.expires_at>:at AND "
    "g.store_allowed AND g.display_allowed\n"
    " AND g.daily_allowance>0 AND license.store_permission='allowed'\n"
    " AND license.display_permission='allowed' AND "
    "license.retention_days>=1\n"
    " ORDER BY metadata_ready DESC,s.id LIMIT 1\n"
    ") candidate ON true\n"
    "LEFT JOIN provider_acquisition_days day ON day.owner_id=:owner "
    "AND day.provider_id=p.id AND day.utc_day=:utc_day\n"
    "LEFT JOIN provider_acquisition_slots slot ON "
    "slot.owner_id=:owner AND slot.provider_id=p.id\n"
    "LEFT JOIN provider_acquisition_attempts active ON "
    "active.owner_id=:owner AND active.id=slot.attempt_id\n"
    "ORDER BY f.ordinal\n"
)
